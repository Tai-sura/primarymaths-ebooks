import puppeteer from "puppeteer-core";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const b = await puppeteer.launch({ executablePath: "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", headless: "new" });
const p = await b.newPage();
const errs = []; p.on("pageerror", (e) => errs.push(String(e).slice(0, 200)));
await p.setViewport({ width: 1180, height: 900, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await p.goto("https://tai-sura.github.io/primarymaths-ebooks/reader.html?book=p5m07a", { waitUntil: "networkidle0" });
await sleep(2500);
const mount = await p.evaluate(() => ({ plays: document.querySelectorAll(".ans-play").length, shown: document.querySelectorAll(".ln.stamp-line:not(.hid)").length }));
console.log("mount", JSON.stringify(mount));
await p.evaluate(() => { location.hash = "p3"; });
await sleep(900);
const at = await p.evaluate(() => { const el = document.querySelector('.ans-play[data-q="q2"]'); const r = el.getBoundingClientRect(); return { x: r.left + r.width / 2, y: r.top + r.height / 2 }; });
await p.touchscreen.tap(at.x, at.y);
await sleep(600);
console.log("q2 after play:", await p.evaluate(() => document.querySelectorAll('.qa.stamp[data-q="q2"] .ln:not(.hid)').length));
await p.screenshot({ path: process.env.TEMP + "\\p5live-play.png" });
console.log("errors", errs.length ? JSON.stringify(errs.slice(0,2)) : "none");
await b.close();
