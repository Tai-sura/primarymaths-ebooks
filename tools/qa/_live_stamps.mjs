import puppeteer from "puppeteer-core";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const b = await puppeteer.launch({ executablePath: "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", headless: "new" });
const p = await b.newPage();
const errs = []; const bad = [];
p.on("pageerror", (e) => errs.push(String(e).slice(0, 200)));
p.on("response", (r) => { if (r.status() >= 400) bad.push(`${r.status()} ${r.url()}`); });
await p.setViewport({ width: 1180, height: 900, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await p.goto("https://tai-sura.github.io/primarymaths-ebooks/reader.html?book=p5m07a", { waitUntil: "networkidle0" });
await sleep(2500);
const info = await p.evaluate(() => ({ stamps: document.querySelectorAll(".ans-stamp").length, cards: document.querySelectorAll(".qa.card").length }));
console.log("mount", JSON.stringify(info));
await p.evaluate(() => { location.hash = "p3"; });
await sleep(900);
await p.screenshot({ path: process.env.TEMP + "\\p5live-stamps.png" });
await p.evaluate(() => { location.hash = "p10"; });
await sleep(900);
await p.screenshot({ path: process.env.TEMP + "\\p5live-stamps-p10.png" });
console.log("errors", errs.length ? JSON.stringify(errs.slice(0, 2)) : "none", "bad", bad.length ? JSON.stringify(bad.slice(0, 2)) : "none");
await b.close();
